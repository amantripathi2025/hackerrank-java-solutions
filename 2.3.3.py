print("Demonstrating break statement")
for i in range(1, 6):
    if i == 3:
        break
    print(i)

print("\nDemonstrating continue statement")
for i in range(1, 6):
    if i == 3:
        continue
    print(i)

print("\nDemonstrating pass statement")
for i in range(1, 6):
    if i == 3:
        pass
    print(i)